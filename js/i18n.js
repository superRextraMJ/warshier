  let language = DEFAULT_LANGUAGE;

  function t(key, values) {
    const dict = I18N[language] || I18N[DEFAULT_LANGUAGE];
    const fallback = I18N[DEFAULT_LANGUAGE];
    let text = Object.prototype.hasOwnProperty.call(dict, key) ? dict[key] : fallback[key];
    if (typeof text !== 'string') return key;
    if (!values) return text;
    return text.replace(/\{(\w+)\}/g, function (match, name) {
      return Object.prototype.hasOwnProperty.call(values, name) ? String(values[name]) : match;
    });
  }

  window.AppI18n = {
    t: t,
    setLanguage: function (next) {
      language = Object.prototype.hasOwnProperty.call(I18N, next) ? next : DEFAULT_LANGUAGE;
    },
    getLanguage: function () {
      return language;
    },
    hasLanguage: function (next) {
      return Object.prototype.hasOwnProperty.call(I18N, next);
    },
    languages: Object.keys(I18N),
    defaultLanguage: DEFAULT_LANGUAGE
  };
